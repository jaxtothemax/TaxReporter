export type FursCountry = (typeof FURS_COUNTRIES)[number];

const KNOWN: ReadonlySet<string> = new Set(FURS_COUNTRIES);

export function isFursCountry(code: string): code is FursCountry {
  return KNOWN.has(code);
}

/**
 * The FURS code for an ISO 3166-1 alpha-2 code, or null when FURS has none.
 * Only Greece differs: ISO's GR is FURS's EL.
 */
export function fursCountryFromIso(code: string): FursCountry | null {
  const mapped = code === "GR" ? "EL" : code;
  return isFursCountry(mapped) ? mapped : null;
}
